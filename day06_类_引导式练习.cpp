#include <iostream>
#include <string>

// ------------------------------------------------------------
//  我们要做的类：Target —— 一个"检测目标"
//  为什么不用 DetFrame：Target 只有 1 个成员，能看清每一行在干什么。
// ------------------------------------------------------------
class Target {

// 【知识点 A】访问控制
//   public:    下面写的，类外面能访问
//   private:   下面的，只有类自己的函数能用
//   class 默认是 private，struct 默认是 public —— 这就是它俩唯一的区别。
public:

    // --------------------------------------------------------
    // 【知识点 B】构造函数
    //   · 名字必须和类名一模一样（Target）
    //   · 没有返回类型，连 void 都不写
    //   · 造对象时自动调用，你不能手动调它
    //   · 下面这个不带参数，叫"默认构造函数"，所以 Target a; 能编译
    //   · 冒号后面这一串叫"初始化列表"：创建的时候就把值带上
    // --------------------------------------------------------
    Target()
        : depth_(-1.0f)   // 【空1】现在初值是 0.0f，不对。
                         //   "还没测距"应该用一个负数当标记，改成 -1.0f。
                         //   照抄 demo 第 2 节：   Counter() : n_(0) { }
    {
        // 函数体空着，因为值已经在冒号后面给过了。
        // 如果在函数体里写 depth_ = -1.0f; 效果也一样，
        // 但那是"先把对象建好、再赋值"，冒号写法是"创建时就带上值"。
    }

    // --------------------------------------------------------
    // 【知识点 C】带参构造函数
    //   Target t(3.5f);   ← 括号里的 3.5f 会传给形参 d
    //   Target t{3.5f};   ← 花括号写法，效果完全一样
    //   形参 d 只在构造函数内部有效，它不占成员的空间。
    // --------------------------------------------------------
    Target(float d)
        : depth_(d)   // 【空2】这里把形参 d 丢掉了，永远存 0。
                         //   改成用 d 初始化 depth_。
                         //   照抄 demo 第 2 节：  Counter(int n) : n_(n) { }
                         //   改了之后那条 "unused parameter" 警告会消失。
    {
    }

    // --------------------------------------------------------
    // 【知识点 D】成员函数 + const
    //   这个函数只"读"成员、不改，所以末尾要加 const。
    //   加了 const 的意思：我保证不改对象，你可以放心让 const Target& 调我。
    // --------------------------------------------------------
    float depth() const{ return depth_; }
    //             ↑ 【空3】这里少了一个关键字。
    //               先别改，直接去编译，看完那条报错再回来补。

    // --------------------------------------------------------
    // 【知识点 E】要改成员的函数，就不能加 const
    //   这个函数改了 depth_，如果加 const 会编译不过（反方向的错）。
    //   注意这里没有冒号 —— 冒号只在构造函数里有，普通函数没有。
    // --------------------------------------------------------
    void setDepth(float d) {
        depth_ = d;
    }

    // --------------------------------------------------------
    // 【知识点 F】把"业务规则"写进类里
    //   depth_ >= 0 才算"测到了"。
    //   为什么用 >= 0 而不是 != 0：SGBM 匹配失败时视差是 0，
    //   而"0 米"是最近的危险目标，绝不能当成"没测"。
    // --------------------------------------------------------
    bool isMeasured() const {
        return depth_ >=0;     // 【空4】现在永远返回 true，等于没判。
                         //   改成真正的判据：depth_ 大于等于 0 就算测到了。
    }

    // --------------------------------------------------------
    // 【知识点 G】返回字符串的成员函数
    //   条件 ? 真的结果 : 假的结果      ← 这叫三目运算符
    // --------------------------------------------------------
    std::string status() const {
        return isMeasured()?"已测距":"未测距";     // 【空5】改成三目运算符，已测距返回 "已测距"，否则 "未测距"。
                         //   格式：  isMeasured() ? "已测距" : "未测距"
                         //   直接调 isMeasured() 就行，它是自己类里的函数。
                         //   注意：这一空依赖 空4，空4 没填对这里也不会对。
    }

private:
    // 【知识点 H】数据放 private
    //   变量名末尾加下划线，是为了和形参 d 区分开。
    //   不这么写、又把形参也起名 depth_ 的话，-Wshadow 会警告"形参遮蔽了成员"。
    float depth_;
};

// ============================================================
//  下面是测试，不要改。
//  10 个 PASS、零警告，就是过关。
//
//  关于浮点数用 == 比较：
//  正常项目里不该这么写（浮点有误差，要比"差的绝对值小于一个小量"）。
//  这里 -1.0f / 3.5f / 7.0f 都能被 float 精确表示，所以 == 是安全的。
// ============================================================
static int g_pass = 0;
static int g_fail = 0;

static void check(bool ok, const char *what) {
    if (ok) {
        std::cout << "  [PASS] " << what << "\n";
        ++g_pass;
    } else {
        std::cout << "  [FAIL] " << what << "\n";
        ++g_fail;
    }
}

int main() {
    std::cout << "===== 一、三种造对象的方式 =====\n";

    Target a;            // 调 Target()      → depth_ 应该是 -1.0f
    Target b(3.5f);      // 调 Target(float) → 3.5
    Target c{7.0f};      // 调 Target(float) → 7.0，和 b(3.5f) 完全等价

    check(a.depth() == -1.0f, "空1：默认构造后 depth_ 是 -1.0f");
    check(b.depth() == 3.5f,  "空2：b(3.5f) 之后 depth_ 是 3.5f");
    check(c.depth() == 7.0f,  "Target c{7.0f} 和 b(3.5f) 是同一种构造");

    std::cout << "\n===== 二、const 成员函数 =====\n";

    // 拿一个"只读引用"指向 a。
    // 加了 const 之后，编译器只允许你调 const 成员函数。
    const Target &ca = a;
    check(ca.depth() == -1.0f, "空3：const 引用也能调 depth()（说明 const 加对了）");

    std::cout << "\n===== 三、把业务规则写进类里 =====\n";

    check(a.isMeasured() == false, "空4：-1.0f 应该判为未测距");
    check(b.isMeasured() == true,  "空4：3.5f 应该判为已测距");

    std::cout << "\n===== 四、三目运算符 =====\n";

    check(a.status() == "未测距", "空5：a.status() 是 未测距");
    check(b.status() == "已测距", "空5：b.status() 是 已测距");

    std::cout << "\n===== 五、改成员 + 引用到底是什么 =====\n";

    a.setDepth(2.0f);
    check(a.depth() == 2.0f, "setDepth 能改成员（这个函数没加 const，所以能改）");

    // 这一条最值钱：ca 是 a 的"另一个名字"，不是拷贝。
    check(ca.depth() == 2.0f,
          "const 引用看到的是同一块数据（说明 & 不是拷贝）");

    std::cout << "\n==========================================\n";
    std::cout << "  通过 " << g_pass << " / 失败 " << g_fail << "\n";
    std::cout << "  别忘了看警告：这一关要求【零警告】\n";
    std::cout << "==========================================\n";
    return 0;
}


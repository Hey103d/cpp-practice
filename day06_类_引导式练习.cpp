//    类不是你之前学的"语法叠加"，它是一整套新东西（访问控制、构造函数、
//    初始化列表、成员函数、const）。直接盲写会卡住，先照着改一遍，
//    手熟了再去写 36 断言那版（day06_类_盲写练习.cpp，那份先放着别管）。
